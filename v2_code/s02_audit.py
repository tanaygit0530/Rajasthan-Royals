"""S2.1: audit of the RR data pack. Writes v2_results/audit/DATA_AUDIT.md (+ csv tables).
Only aggregates are written to v2_results; nothing ball-level leaves v2_work.
"""
from common import *

L = []                       # markdown lines
def h(t): L.append(f'\n## {t}\n')
def p(t=''): L.append(t)
def tbl(df, idx=True): L.append(df.to_markdown(index=idx)); L.append('')

b = rr('ball_by_ball.csv'); m = rr('matches.csv'); c = rr('competitions.csv')
t = rr('teams.csv'); mp = rr('competition_team_player_mapping.csv'); xi = rr('playing_eleven.csv')
m = m.merge(c[['comp_id', 'comp_name', 'match_format']], on='comp_id', how='left')
m['season'] = m.match_date.str[:4].astype(int)
m['comp'] = np.where(m.comp_name.str.startswith('IPL'), 'IPL', np.where(m.match_format.eq('T20I'), 'T20I', 'A-team'))

p('# RR data pack audit'); p(f'Generated by `v2_code/s02_audit.py`. Files: ' + ', '.join(
    f'`{n}` ({len(d):,} rows)' for n, d in [('ball_by_ball', b), ('matches', m), ('competitions', c), ('teams', t),
                                             ('competition_team_player_mapping', mp), ('playing_eleven', xi)]))

# ---- coverage
h('1. Coverage by competition type and season')
bm = set(b.match_id)
m['has_balls'] = m.match_id.isin(bm)
cov = m.pivot_table(index='comp', columns='season', values='match_id', aggfunc='count', fill_value=0)
p('Matches in `matches.csv`:'); tbl(cov)
cov2 = m[m.has_balls].pivot_table(index='comp', columns='season', values='match_id', aggfunc='count', fill_value=0)
p('Matches with ball-by-ball data:'); tbl(cov2)
nob = m[~m.has_balls]
p(f'{len(nob)} matches have no ball data (results: {nob.result.fillna("NA").str[:40].value_counts().head(5).to_dict()}).')
p(f'{len(bm - set(m.match_id))} match_ids in ball data are missing from matches.csv.')
nat = m[m.comp == 'T20I']
teams_t20i = pd.concat([nat.home_team, nat.away_team]).value_counts()
p(f'\nT20I teams (matches): ' + ', '.join(f'{k} {v}' for k, v in teams_t20i.items()))

# ---- columns
h('2. Data dictionary — ball_by_ball.csv')
DESC = {
 'match_id': 'Match key (joins matches.csv)', 'innings': '1, 2 = regulation; 3, 4 = super over', 'overid': 'Over number, 1-based',
 'over_ball_num': 'Ball number within over (incl. extras)', 'innings_ball_num': 'Running delivery count in innings',
 'batting_team_id': 'Team id (teams.csv)', 'bowling_team_id': 'Team id', 'striker_id': 'Batter on strike (player id)',
 'striker_name': 'Name', 'non_striker_id': 'Non-striker id', 'non_striker_name': 'Name', 'bowler_id': 'Bowler id',
 'bowler_name': 'Name', 'batting_type': 'Striker hand: RHB / LHB', 'bowling_type': 'Bowler style (12 classes)',
 'batting_order': 'Striker batting position', 'runs': 'Runs off the bat', 'is_four': 'Boundary four', 'is_six': 'Six',
 'is_wicket': 'Wicket on this delivery (any type)', 'dismissal_type_id': 'Code for dismissal_type',
 'dismissal_type': 'Caught/Bowled/LBW/RunOut/Stump/Hit Wicket/Retire Out/Obstructing', 'dismissed_player_id': 'Who was out',
 'extras_type': 'wide / legbyes / byes / Overstep (no-ball) / other (no-ball) / Penalty', 'extras1_runs': 'Extras runs (main)',
 'extras_2_runs': 'Extras runs (secondary, e.g. no-ball + byes)', 'pace_or_spin': 'Pace / Spin',
 'bowl_speed': 'Release speed (0 = missing)', 'stroke': 'Shot played (free text categories)',
 'delivery_style': 'Delivery type (e.g. Inswing, Googly, Full Toss)', 'over_or_around': 'Bowler over/around the wicket',
 'on_or_off': 'Ball direction on/off side', 'delivery_ist_time': 'Timestamp (date-level reliability only)'}
rows = []
for col in b.columns:
    s = b[col]
    rows.append(dict(column=col, dtype=str(s.dtype), missing_pct=round(s.isna().mean() * 100, 2),
                     n_unique=s.nunique(), example=str(s.dropna().iloc[0])[:30] if s.notna().any() else '',
                     meaning=DESC.get(col, '')))
tbl(pd.DataFrame(rows), idx=False)

# ---- quirks
h('3. Quirks and checks')
bb = b.merge(m[['match_id', 'comp', 'season']], on='match_id', how='left')
p(f'- Super-over deliveries (innings 3/4): {int((b.innings > 2).sum())} — excluded.')
et = b.extras_type.fillna('')
p(f'- extras_type counts: {et.replace("", "none").value_counts().to_dict()}. `Overstep` and `other` behave as no-balls '
  f'(not counted as legal). `other` appears {int(et.eq("other").sum())} times — checked below.')
oth = b[et.eq('other')]
p(f'  - `other` rows: extras1_runs distribution {oth.extras1_runs.value_counts().head(4).to_dict()}, '
  f'over_ball_num repeats next ball in same over: {round(((b.shift(-1).over_ball_num == b.over_ball_num) & et.eq("other")).sum() / max(len(oth),1),2)} share.')
p(f'- Dismissal labels: {b.dismissal_type.value_counts().to_dict()} (note the misspelling "Obstracting").')
nsd = b[b.is_wicket & b.dismissed_player_id.notna() & (b.dismissed_player_id != b.striker_id)]
p(f'- Wickets where the dismissed player is the non-striker: {len(nsd)} (types: {nsd.dismissal_type.value_counts().to_dict()}).')
sp = bb.assign(z=b.bowl_speed.fillna(0).eq(0)).groupby(['comp', 'season']).z.mean().unstack().round(3)
p('- `bowl_speed` missing (0) share by competition x season:'); tbl(sp)
ds = bb.assign(z=b.delivery_style.isna()).groupby(['comp', 'season']).z.mean().unstack().round(3)
p('- `delivery_style` missing share:'); tbl(ds)
st = bb.assign(z=b.stroke.isna()).groupby(['comp', 'season']).z.mean().unstack().round(3)
p('- `stroke` missing share:'); tbl(st)
legal = ~et.isin(['wide', 'Overstep', 'other'])
lb = b[b.innings <= 2].assign(l=legal).groupby(['match_id', 'innings']).l.sum()
p(f'- Legal balls per innings: max {int(lb.max())}, innings with >120 legal balls: {int((lb > 120).sum())}.')
ov = b.groupby(['match_id', 'innings', 'overid']).apply(lambda d: (~d.extras_type.fillna('').isin(['wide', 'Overstep', 'other'])).sum(), include_groups=False)
p(f'- Overs with legal-ball count != 6 (excluding the last over of an innings): '
  f'{int(((ov != 6) & (ov.groupby(level=[0, 1]).transform(lambda s: s.index.get_level_values(2) != s.index.get_level_values(2).max()))).sum())}.')
p(f'- Rain-revised matches: {int(m[["first_inn_revised_overs", "second_inn_revised_overs", "revised_target"]].notna().any(axis=1).sum())}; '
  f'no-result (no winner) with ball data: {int((m.has_balls & m.win_team_id.isna()).sum())}; knockouts: {int(m.knock_out.eq(1).sum())}; '
  f'stage values: {m.stage.value_counts().to_dict()}.')

# ---- identity consistency
h('4. Player identity consistency')
names = pd.concat([b[['striker_id', 'striker_name']].set_axis(['pid', 'name'], axis=1),
                   b[['bowler_id', 'bowler_name']].set_axis(['pid', 'name'], axis=1),
                   b[['non_striker_id', 'non_striker_name']].set_axis(['pid', 'name'], axis=1)]).drop_duplicates()
multi_name = names.groupby('pid').name.nunique()
p(f'- Distinct player ids in ball data: {names.pid.nunique():,}. Ids with >1 spelling: {int((multi_name > 1).sum())}.')
if (multi_name > 1).any():
    tbl(names[names.pid.isin(multi_name[multi_name > 1].index)].sort_values('pid').head(30), idx=False)
multi_id = names.groupby('name').pid.nunique()
dup = names[names.name.isin(multi_id[multi_id > 1].index)].sort_values('name')
p(f'- Names shared by >1 id: {int((multi_id > 1).sum())} (must never be merged by name):')
if len(dup): tbl(dup.head(40), idx=False)
mpn = mp.groupby('player_id').player_name.nunique()
p(f'- In competition_team_player_mapping, ids with >1 name: {int((mpn > 1).sum())}.')
bt = b.groupby('bowler_id').bowling_type.nunique()
p(f'- Bowlers with >1 bowling_type label across their balls: {int((bt > 1).sum())} of {len(bt)}.')
bh = b.groupby('striker_id').batting_type.nunique()
p(f'- Batters with >1 batting hand label: {int((bh > 1).sum())} of {len(bh)}.')

# ---- playing XI
h('5. playing_eleven.csv')
xi = xi.merge(m[['match_id', 'comp', 'season']], on='match_id', how='left')
p(f'- Rows {len(xi):,}; is_impact share by comp x season:'); tbl(xi.groupby(['comp', 'season']).is_impact.mean().unstack().round(3))
p(f'- Players per team-match: {xi.groupby(["match_id", "team_id"]).size().describe().round(1).to_dict()}')

open(res('audit/DATA_AUDIT.md'), 'w').write('\n'.join(L))
print('\n'.join(L)[:12000])
